/**
 * The packages as an app gets them (angular.md 6, ARCHITECTURE §1; Phase 8b, the entries check taken from DzTooltip's
 * scripts/entries.mjs): the six built packages packed, installed in a fresh app of each Angular major with that major's
 * compiler and TypeScript, DzGrid and DzTooltip from npm through the bridges' ranges. Two files compiled by `ngc`, strict
 * templates, `skipLibCheck: false`, an app's strictest options (`exactOptionalPropertyTypes`, `noUncheckedIndexedAccess`):
 * the components in a template, and every typed entry of the six imported and wired to a real grid and a real tooltip —
 * a bridge's structural types that a real DzGrid does not fit fail here (Phase 8a found one). The theme's sheets must be
 * in its package. Needs the network (npm); not in the gate — run at a phase close and before a release:
 * `npm run build && node scripts/angular-compat.mjs [19 20 21 22]`.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const majors = process.argv.slice(2).length ? process.argv.slice(2) : ['19', '20', '21', '22'];
const run = (cmd, args, cwd) => execFileSync(cmd, args, { cwd, stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8' });

// The packages as an app installs them: packed from their dist/.
const packed = mkdtempSync(join(tmpdir(), 'dzgraph-packed-'));
const PACKAGES = ['core', 'dom', 'theme', 'angular', 'dztooltip', 'dzgrid'];
for (const p of PACKAGES) run('npm', ['pack', '--pack-destination', packed], join(root, 'packages', p, 'dist'));
const tarballs = readdirSync(packed).map((f) => join(packed, f));

const APP = `import { Component, signal } from '@angular/core';
import { DzChart, DzSparkline } from '@dzgraph/angular';
import type { ChartOptions } from '@dzgraph/core';

@Component({
  selector: 'app-root',
  imports: [DzChart, DzSparkline],
  template: \`<dz-chart [options]="options()" (pointClick)="clicked = $event.seriesId" (drill)="path = $event.path" (viewChange)="changed = $event.changed" />
<dz-sparkline [values]="values()" [options]="{ type: 'area', label: 'Visits' }" />\`,
})
export class App {
  readonly options = signal<ChartOptions>({ series: [{ type: 'line', data: [1, 2, 3] }] });
  readonly values = signal<readonly number[]>([1, 5, 4]);
  clicked = '';
  path: readonly string[] = [];
  changed: readonly string[] = [];
}
`;

/** Every typed entry of the six, imported, and the bridges wired to a real DzGrid grid and DzTooltip. */
const typed = PACKAGES.flatMap((p) => {
  const m = JSON.parse(readFileSync(join(root, 'packages', p, 'dist', 'package.json'), 'utf8'));
  return Object.entries(m.exports ?? {})
    .filter(([k, v]) => k !== './package.json' && typeof v === 'object' && v !== null && 'types' in v)
    .map(([k]) => (k === '.' ? m.name : `${m.name}/${k.slice(2)}`));
});
const ENTRIES = `// Generated by scripts/angular-compat.mjs: every typed entry, the bridges on a real grid.
${typed.map((e, i) => `import * as e${i} from '${e}';`).join('\n')}
import { allTypes, type ChartOptions } from '@dzgraph/core';
import { allFeatures, chart, type Chart } from '@dzgraph/dom';
import { sparkline } from '@dzgraph/dom/sparkline';
import { sparklineOf } from '@dzgraph/core/sparkline';
import { dzTooltip } from '@dzgraph/dztooltip';
import { chartFromGrid, chartMenuItem, gridTable, linkGrid } from '@dzgraph/dzgrid';
import { createGrid } from '@dzgrid/dom';
import { EN } from '@dzgrid/dom/locales/en';
import { range } from '@dzgrid/dom/range';
import { grouping } from '@dzgrid/dom/grouping';
import { pivot } from '@dzgrid/dom/pivot';
import { contextMenu } from '@dzgrid/dom/context-menu';

export const entries: readonly object[] = [${typed.map((_, i) => `e${i}`).join(', ')}];
type Row = { readonly id: string; readonly month: string; readonly sales: number };
export function wire(el: HTMLElement, host: HTMLElement): number {
  const options: ChartOptions = { series: [{ type: 'line', id: 's', data: [{ x: 'Jan', y: 1, key: 'a' }] }] };
  const c: Chart = chart(el, options, { types: allTypes, features: [...allFeatures, dzTooltip({ tone: 'info', placement: 'top' })] });
  const blocks = range();
  const p = pivot({ columns: ['month'], values: { sales: 'sum' } });
  const menu = contextMenu<Row>({ items: (_c, defaults) => [...defaults, chartMenuItem('Chart', (ctx) => void ctx.key)] });
  const grid = createGrid<Row>(host, { rows: [], getRowId: (r) => r.id, messages: EN, columns: [{ id: 'month' }, { id: 'sales', type: 'number' }], features: [blocks, menu, grouping({ by: ['month'], pivot: p })] });
  const stops = [linkGrid(c, grid, { filter: { column: 'sales', by: 'range', as: 'number' } }), chartFromGrid(c, grid, { range: blocks, pivot: p, type: 'column', yesNo: ['Yes', 'No'] })];
  const n = gridTable(grid, { range: blocks }).series.length + (sparklineOf([1, null, 3]).summary?.count ?? 0);
  sparkline(el, [1, 2, 3], { type: 'area' }).destroy();
  stops.forEach((stop) => stop());
  grid.destroy();
  c.destroy();
  return n;
}
`;
const sheets = ['dzgraph.css', 'dzgraph.unlayered.css', 'dzgraph.scss'];

let failed = 0;
for (const major of majors) {
  const dir = mkdtempSync(join(tmpdir(), `dzgraph-ng${major}-`));
  try {
    // The newest TypeScript that major's compiler takes (its peer range).
    // Asked for a major, npm answers per version: the last is the newest.
    const range = [JSON.parse(run('npm', ['view', `@angular/compiler-cli@${major}`, 'peerDependencies', '--json'], dir))].flat().at(-1).typescript;
    const versions = JSON.parse(run('npm', ['view', `typescript@${range}`, 'version', '--json'], dir));
    const typescript = [versions].flat().filter((v) => !v.includes('-')).at(-1);
    writeFileSync(join(dir, 'package.json'), JSON.stringify({ name: `compat-${major}`, private: true, type: 'module' }));
    const ng = ['core', 'common', 'compiler', 'compiler-cli', 'platform-browser'].map((p) => `@angular/${p}@${major}`);
    // No legacy-peer-deps: a bridge's peer range that npm cannot meet fails the install.
    writeFileSync(join(dir, '.npmrc'), 'legacy-peer-deps=false\n');
    run('npm', ['install', '--no-audit', '--no-fund', ...ng, 'rxjs@7', 'tslib@2', `typescript@${typescript}`, '@dztooltip/core@1', '@dzgrid/core@1', '@dzgrid/dom@1', ...tarballs], dir);
    const lost = sheets.filter((f) => !existsSync(join(dir, 'node_modules/@dzgraph/theme', f)));
    if (lost.length) throw new Error(`@dzgraph/theme lacks ${lost.join(', ')}`);
    mkdirSync(join(dir, 'src'));
    writeFileSync(join(dir, 'src', 'app.ts'), APP);
    writeFileSync(join(dir, 'src', 'entries.ts'), ENTRIES);
    writeFileSync(
      join(dir, 'tsconfig.json'),
      JSON.stringify({
        compilerOptions: { target: 'ES2022', module: 'ES2022', moduleResolution: 'bundler', strict: true, exactOptionalPropertyTypes: true, noUncheckedIndexedAccess: true, skipLibCheck: false, lib: ['ES2023', 'DOM', 'DOM.Iterable'], outDir: 'out', rootDir: 'src', declaration: false, useDefineForClassFields: false },
        files: ['src/app.ts', 'src/entries.ts'],
        angularCompilerOptions: { strictTemplates: true, strictInjectionParameters: true },
      }),
    );
    const version = run('node', ['-e', "console.log(require('@angular/core/package.json').version)"], dir).trim();
    run('npx', ['ngc', '-p', 'tsconfig.json'], dir);
    console.log(`ok   Angular ${version} (TypeScript ${typescript}): ${typed.length} typed entries and the bridges compiled, the theme's sheets there`);
  } catch (e) {
    failed++;
    console.error(`FAIL Angular ${major}\n${e.stdout ?? ''}${e.stderr ?? e.message}`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}
rmSync(packed, { recursive: true, force: true });
process.exit(failed ? 1 : 0);
